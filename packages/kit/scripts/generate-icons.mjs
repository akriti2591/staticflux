#!/usr/bin/env node
/**
 * Generate the kit's icon modules (STUDIO-UX-SPEC §10.2 point 5): one TypeScript module per icon in
 * `packages/kit/src/icons/<name>.ts` exporting `<camelName>Icon` (an `IconDef`), plus the
 * `index.ts` barrel.
 *
 * - Lucide icons: the names in `src/icons/icons.json`, read from the `lucide` dev dependency
 *   (ISC; Feather-derived icons MIT — see `src/icons/LICENSE`). Aliases resolve to the current icon,
 *   the module keeps the requested name.
 * - Custom icons: every `src/icons/custom/*.svg` (same 24-unit viewBox and stroke attributes as
 *   Lucide); only path / circle / rect / line / polyline / polygon / ellipse children are read.
 *
 * `--check` writes nothing and exits 1 when a module is missing or differs (the kit test runs it).
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, unlinkSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const KIT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ICONS = join(KIT, 'src', 'icons');
const CUSTOM = join(ICONS, 'custom');
const check = process.argv.includes('--check');

const pascal = (name) => name.split('-').map((part) => part[0].toUpperCase() + part.slice(1)).join('');
const camel = (name) => {
  const p = pascal(name);
  return p[0].toLowerCase() + p.slice(1);
};
const exportName = (name) => `${camel(name)}Icon`;

const TAGS = new Set(['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse']);
const ATTR = /^(?:d|cx|cy|r|rx|ry|x|y|x1|x2|y1|y2|width|height|points|fill|fill-opacity|stroke|stroke-dasharray|stroke-width|opacity|transform)$/;

/** Child nodes of a custom SVG file (tag + allowed attributes, in order). */
function parseSvg(text, file) {
  if (!/viewBox="0 0 24 24"/.test(text)) throw new Error(`${file}: viewBox must be "0 0 24 24"`);
  const nodes = [];
  for (const m of text.matchAll(/<([a-z]+)\b([^>]*?)\/?>/g)) {
    const tag = m[1];
    if (tag === 'svg' || tag === 'title') continue;
    if (!TAGS.has(tag)) throw new Error(`${file}: <${tag}> is not allowed`);
    const attributes = {};
    for (const a of m[2].matchAll(/([a-z-]+)="([^"]*)"/g)) {
      if (!ATTR.test(a[1])) throw new Error(`${file}: attribute "${a[1]}" is not allowed`);
      attributes[a[1]] = a[2];
    }
    nodes.push([tag, attributes]);
  }
  if (nodes.length === 0) throw new Error(`${file}: no shapes`);
  return nodes;
}

function moduleText(name, nodes, source) {
  const lines = nodes.map(([tag, attrs]) => `  [${JSON.stringify(tag)}, ${JSON.stringify(attrs).replace(/":/g, '": ').replace(/,"/g, ', "')}],`);
  const origin =
    source === 'lucide'
      ? `Lucide \`${name}\` (lucide.dev, ISC; see ./LICENSE).`
      : `Custom icon \`${name}\` (./custom/${name}.svg), drawn on Lucide's grid.`;
  return `// Generated by packages/kit/scripts/generate-icons.mjs. Do not edit.\n/** ${origin} */\nimport { defineIcon } from '../icon-def.js';\n\nexport const ${exportName(name)} = /* @__PURE__ */ defineIcon(${JSON.stringify(name)}, [\n${lines.join('\n')}\n], ${JSON.stringify(source)});\n`;
}

const manifest = JSON.parse(readFileSync(join(ICONS, 'icons.json'), 'utf8'));
const require = createRequire(join(KIT, 'package.json'));
const lucideEntry = join(dirname(require.resolve('lucide/package.json')), 'dist', 'esm', 'iconsAndAliases.mjs');
const lucide = await import(pathToFileURL(lucideEntry).href);

const modules = new Map();
const missing = [];
for (const name of manifest.lucide) {
  const nodes = lucide[pascal(name)];
  if (!Array.isArray(nodes)) missing.push(name);
  else modules.set(name, moduleText(name, nodes, 'lucide'));
}
if (missing.length > 0) {
  console.error(`Not in Lucide: ${missing.join(', ')}`);
  process.exit(2);
}
for (const file of existsSync(CUSTOM) ? readdirSync(CUSTOM).filter((f) => f.endsWith('.svg')).sort() : []) {
  const name = file.slice(0, -4);
  if (modules.has(name)) throw new Error(`custom/${file} clashes with the Lucide icon "${name}"`);
  modules.set(name, moduleText(name, parseSvg(readFileSync(join(CUSTOM, file), 'utf8'), file), 'custom'));
}

const names = [...modules.keys()].sort();
const barrel = `// Generated by packages/kit/scripts/generate-icons.mjs. Do not edit.\n/** Every kit icon (Lucide + custom). Prefer the per-icon modules (\`@staticflux/kit/icons/<name>\`) in boot paths. */\n${names.map((n) => `export { ${exportName(n)} } from './${n}.js';`).join('\n')}\n`;
const wanted = new Map([...modules].map(([n, text]) => [`${n}.ts`, text]));
wanted.set('index.ts', barrel);

let stale = 0;
for (const [file, text] of wanted) {
  const path = join(ICONS, file);
  const current = existsSync(path) ? readFileSync(path, 'utf8') : undefined;
  if (current === text) continue;
  stale += 1;
  if (check) console.error(`out of date: src/icons/${file}`);
  else writeFileSync(path, text);
}
for (const file of readdirSync(ICONS).filter((f) => f.endsWith('.ts') && !wanted.has(f))) {
  stale += 1;
  if (check) console.error(`not generated: src/icons/${file}`);
  else unlinkSync(join(ICONS, file));
}
if (check && stale > 0) process.exit(1);
console.log(`${names.length} icons${check ? ' up to date' : ` written (${stale} changed)`}.`);
