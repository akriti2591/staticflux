/**
 * `sf errors` — the machine-readable error catalog `docs/errors.json` (§13).
 *
 * Importing a module evaluates its `defineError` calls, which register in
 * core's catalog (`listErrorDefinitions()`). Because a module may resolve a
 * different copy of `@staticflux/core` than the CLI does, exported
 * `ErrorDefinition` values are also collected directly from each module's
 * exports. Both sources are merged by code; conflicting duplicates are reported.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { type ErrorKind, listErrorDefinitions, type SfError } from '@staticflux/core';
import { ErrorCatalogConflict } from './errors.js';
import { expandGlob, importModule, type ModuleImporter, readText } from './files.js';

export interface ErrorCatalogEntry {
  readonly code: string;
  readonly kind: ErrorKind;
  readonly summary: string;
  readonly fix: string;
}

export interface ErrorCatalog {
  readonly version: 1;
  readonly description: string;
  readonly errors: readonly ErrorCatalogEntry[];
}

export interface CollectErrorsOptions {
  readonly cwd: string;
  /** Module paths or globs; default `packages/*\/dist/index.js`. */
  readonly modules?: readonly string[];
  readonly importer?: ModuleImporter;
  /** Source of registered definitions; default core's `listErrorDefinitions`. */
  readonly listDefinitions?: () => readonly ErrorCatalogEntry[];
}

export interface CollectErrorsResult {
  readonly catalog: ErrorCatalog;
  readonly loaded: readonly string[];
  /** Modules that failed to import (non-fatal unless `--strict`). */
  readonly failures: readonly SfError[];
  readonly conflicts: readonly SfError[];
}

export const DEFAULT_ERROR_MODULES = ['packages/*/dist/index.js'] as const;

function asEntry(value: unknown): ErrorCatalogEntry | undefined {
  if (typeof value !== 'function' && (typeof value !== 'object' || value === null)) return undefined;
  const v = value as Record<string, unknown>;
  const { code, kind, summary, fix } = v;
  if (typeof code !== 'string' || typeof kind !== 'string' || typeof summary !== 'string' || typeof fix !== 'string') return undefined;
  if (!/^[A-Z][A-Z0-9]*-/.test(code)) return undefined;
  return { code, kind: kind as ErrorKind, summary, fix };
}

export async function collectErrorCatalog(options: CollectErrorsOptions): Promise<CollectErrorsResult> {
  const patterns = options.modules !== undefined && options.modules.length > 0 ? options.modules : DEFAULT_ERROR_MODULES;
  const paths = [...new Set(patterns.flatMap((p) => expandGlob(p, options.cwd)))];
  const failures: SfError[] = [];
  const loaded: string[] = [];
  const found: ErrorCatalogEntry[] = [];
  for (const path of paths) {
    const result = await importModule(path, options.cwd, options.importer);
    if (!result.ok) {
      failures.push(result.error);
      continue;
    }
    loaded.push(path);
    for (const value of Object.values(result.value)) {
      const entry = asEntry(value);
      if (entry !== undefined) found.push(entry);
    }
  }
  const registered = (options.listDefinitions ?? listErrorDefinitions)();

  const byCode = new Map<string, ErrorCatalogEntry>();
  const conflicts: SfError[] = [];
  for (const entry of [...registered, ...found]) {
    const existing = byCode.get(entry.code);
    if (existing === undefined) {
      byCode.set(entry.code, entry);
    } else if (existing.kind !== entry.kind || existing.summary !== entry.summary || existing.fix !== entry.fix) {
      conflicts.push(ErrorCatalogConflict({ message: `Error code ${entry.code} is defined twice with different metadata.`, details: { first: existing, second: entry } }));
    }
  }
  const errors = [...byCode.values()].sort((a, b) => a.code.localeCompare(b.code));
  return {
    catalog: {
      version: 1,
      description: 'StaticFlux error catalog, generated by `sf errors`. Look codes up here instead of guessing; do not edit by hand.',
      errors,
    },
    loaded,
    failures,
    conflicts,
  };
}

export function serializeErrorCatalog(catalog: ErrorCatalog): string {
  return `${JSON.stringify(catalog, null, 2)}\n`;
}

/** Write the catalog; returns whether the file content changed. */
export function writeErrorCatalog(path: string, catalog: ErrorCatalog): boolean {
  const content = serializeErrorCatalog(catalog);
  if (existsSync(path)) {
    const current = readText(path);
    if (current.ok && current.value === content) return false;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  return true;
}

/** True when the file on disk equals what would be written. */
export function isErrorCatalogCurrent(path: string, catalog: ErrorCatalog): boolean {
  const current = readText(path);
  return current.ok && current.value === serializeErrorCatalog(catalog);
}
