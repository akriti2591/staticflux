/**
 * `sf agents` — keep the generated part of every package `AGENTS.md` in sync
 * with the config CI enforces (R20.2): "Budgets" from `.size-limit.json`,
 * "Allowed dependencies" from `package.json` (`dependencies`,
 * `staticflux.layer`). Only the text between the marker comments is owned by
 * the tool; markers are appended when absent. Hand-written text is untouched.
 */
import { existsSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { err, ok, type Result, type SfError } from '@staticflux/core';
import { checkName, type SizeLimitCheck } from './budgets.js';
import { InvalidJson } from './errors.js';
import { displayPath, expandGlob, readJson, readText } from './files.js';

export const GENERATED_START = '<!-- sf:generated:start -->';
export const GENERATED_END = '<!-- sf:generated:end -->';

export interface PackageInfo {
  /** Directory relative to the repo root, e.g. `packages/core`. */
  readonly dir: string;
  readonly name: string;
  readonly layer: string | undefined;
  readonly dependencies: Readonly<Record<string, string>>;
}

interface PackageJsonShape {
  readonly name?: unknown;
  readonly dependencies?: unknown;
  readonly staticflux?: { readonly layer?: unknown };
}

export function readPackageInfo(root: string, dir: string): Result<PackageInfo> {
  const path = join(root, dir, 'package.json');
  const json = readJson(path);
  if (!json.ok) return json;
  if (typeof json.value !== 'object' || json.value === null) return err(InvalidJson({ message: `${path} is not an object.` }));
  const pkg = json.value as PackageJsonShape;
  const deps: Record<string, string> = {};
  if (typeof pkg.dependencies === 'object' && pkg.dependencies !== null) {
    for (const [k, v] of Object.entries(pkg.dependencies as Record<string, unknown>)) if (typeof v === 'string') deps[k] = v;
  }
  const layer = pkg.staticflux?.layer;
  return ok({ dir, name: typeof pkg.name === 'string' ? pkg.name : basename(dir), layer: typeof layer === 'string' ? layer : undefined, dependencies: deps });
}

function checkPaths(check: SizeLimitCheck): string[] {
  if (typeof check.path === 'string') return [check.path];
  if (Array.isArray(check.path)) return check.path.filter((p): p is string => typeof p === 'string');
  return [];
}

/** Size-limit checks whose path lies inside the package directory. */
export function budgetsForPackage(dir: string, checks: readonly SizeLimitCheck[]): { name: string; limit: string; target: string }[] {
  const prefix = `${dir.replace(/\/+$/, '')}/`;
  return checks.flatMap((check, index) => {
    const paths = checkPaths(check).map((p) => p.replace(/^\.\//, ''));
    if (!paths.some((p) => p.startsWith(prefix))) return [];
    const target = `${paths.join(', ')}${typeof check.import === 'string' ? ` · import \`${check.import}\`` : ''}`;
    return [{ name: checkName(check, index), limit: typeof check.limit === 'string' ? check.limit : '—', target }];
  });
}

/** The generated block, markers included. Deterministic for a given input. */
export function renderGeneratedBlock(info: PackageInfo, checks: readonly SizeLimitCheck[]): string {
  const lines = [GENERATED_START, '<!-- Generated by `sf agents` from package.json and .size-limit.json. Do not edit between these markers. -->', '', '## Budgets', ''];
  const budgets = budgetsForPackage(info.dir, checks);
  if (budgets.length === 0) {
    lines.push('No size budget declared in `.size-limit.json` for this package.');
  } else {
    lines.push('| Check | Limit | Measures |', '|---|---|---|');
    for (const b of budgets) lines.push(`| ${b.name.replace(/\|/g, '\\|')} | ${b.limit} | ${b.target.replace(/\|/g, '\\|')} |`);
    lines.push('', 'Budgets ratchet (R12.8): `sf budgets` proposes tightening; raising one needs a reviewed reason.');
  }
  lines.push('', '## Allowed dependencies', '', `**Layer:** ${info.layer ?? '(not declared — set `staticflux.layer` in package.json)'}`, '');
  const entries = Object.entries(info.dependencies).sort(([a], [b]) => a.localeCompare(b));
  const internal = entries.filter(([name]) => name.startsWith('@staticflux/'));
  const external = entries.filter(([name]) => !name.startsWith('@staticflux/'));
  if (entries.length === 0) lines.push('None. This package may not import any other package.');
  if (internal.length > 0) lines.push(`- Internal: ${internal.map(([n]) => `\`${n}\``).join(', ')}`);
  if (external.length > 0) lines.push(`- External: ${external.map(([n, v]) => `\`${n}\` (${v})`).join(', ')}`);
  if (entries.length > 0) lines.push('', 'Anything else is a boundary violation (`pnpm lint:boundaries`). Adding a dependency needs a reviewed reason.');
  lines.push(GENERATED_END);
  return lines.join('\n');
}

/** Replace the marked block in `content`, or append it (with markers) when absent. */
export function spliceGeneratedBlock(content: string, block: string): string {
  const start = content.indexOf(GENERATED_START);
  const end = content.indexOf(GENERATED_END);
  if (start !== -1 && end > start) {
    return content.slice(0, start) + block + content.slice(end + GENERATED_END.length);
  }
  const base = content.replace(/\s*$/, '');
  return `${base.length > 0 ? `${base}\n\n` : ''}${block}\n`;
}

export interface AgentsUpdate {
  readonly file: string;
  readonly status: 'created' | 'updated' | 'unchanged';
}

export interface AgentsOptions {
  readonly root: string;
  /** Package dir globs relative to root. Default `packages/*`. */
  readonly packages?: readonly string[];
  /** Path to size-limit config relative to root. Default `.size-limit.json`. */
  readonly sizeLimitPath?: string;
  /** Report what would change without writing. */
  readonly check?: boolean;
}

export interface AgentsResult {
  readonly updates: readonly AgentsUpdate[];
  readonly errors: readonly SfError[];
}

export function updateAgentsFiles(options: AgentsOptions): AgentsResult {
  const root = options.root;
  const sizePath = join(root, options.sizeLimitPath ?? '.size-limit.json');
  let checks: SizeLimitCheck[] = [];
  const errors: SfError[] = [];
  if (existsSync(sizePath)) {
    const json = readJson(sizePath);
    if (!json.ok) errors.push(json.error);
    else if (Array.isArray(json.value)) checks = json.value as SizeLimitCheck[];
    else errors.push(InvalidJson({ message: `${sizePath} must be an array of size-limit checks.` }));
  }
  const dirs = (options.packages ?? ['packages/*'])
    .flatMap((p) => expandGlob(p, root))
    .filter((d) => existsSync(join(d, 'package.json')))
    .map((d) => displayPath(d, root));
  const updates: AgentsUpdate[] = [];
  for (const dir of [...new Set(dirs)].sort()) {
    const info = readPackageInfo(root, dir);
    if (!info.ok) {
      errors.push(info.error);
      continue;
    }
    const file = join(root, dir, 'AGENTS.md');
    const exists = existsSync(file);
    const current = exists ? readText(file) : ok(`# ${info.value.name} — AGENTS.md\n`);
    if (!current.ok) {
      errors.push(current.error);
      continue;
    }
    const next = spliceGeneratedBlock(current.value, renderGeneratedBlock(info.value, checks));
    const status: AgentsUpdate['status'] = !exists ? 'created' : next === current.value ? 'unchanged' : 'updated';
    if (status !== 'unchanged' && options.check !== true) writeFileSync(file, next);
    updates.push({ file: displayPath(file, root), status });
  }
  return { updates, errors };
}
