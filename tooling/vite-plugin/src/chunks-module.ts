/**
 * Logical chunk id → bundler chunk mapping.
 *
 * Approach (documented in AGENTS.md):
 * 1. **Build**: every declaration whose `entry` is a module path is emitted as its own named
 *    chunk in `buildStart` (`this.emitFile({ type: 'chunk', id, name })`). The chunk name is the
 *    file-safe logical id (`feature:studio-desktop` → `feature.studio-desktop`), so file names are
 *    stable and readable (`assets/feature.studio-desktop-<hash>.js`), and the chunk boundary exists
 *    even if no code `import()`s the module yet. `createManifest` then maps the chunk back to the
 *    logical id through its facade module path.
 * 2. **App code**: `virtual:sf-chunks` exports `chunks` — `import()` thunks keyed by logical id —
 *    plus `chunkIds` and `importChunk(id)`. Feature manifests use `load: chunks['feature:x']`, so the
 *    same thunk works in dev (no manifest needed) and build (the bundler rewrites it to the hashed file).
 * 3. **Dev**: the dev server serves a dev `sf-manifest.json` whose files are the source modules
 *    (`/src/features/x.ts`), so the loader's URL-based strategies work unchanged under `vite dev`.
 */
import { isAbsolute, relative, resolve, sep } from 'node:path';
import type { BundlerChunk, ChunkDeclaration } from '@staticflux/loader';

export const VIRTUAL_CHUNKS_ID = 'virtual:sf-chunks' as const;
/** Rollup convention: a `\0` prefix marks a virtual module so other plugins skip it. */
export const RESOLVED_VIRTUAL_CHUNKS_ID = `\0${VIRTUAL_CHUNKS_ID}` as const;
/** URL of the virtual module in the dev server (Vite encodes `\0` as `__x00__`). */
export const DEV_VIRTUAL_CHUNKS_URL = `/@id/__x00__${VIRTUAL_CHUNKS_ID}` as const;

/** Types of `virtual:sf-chunks` (declare the module in the app: see AGENTS.md). */
export interface SfChunksModule {
  readonly chunks: Readonly<Record<string, () => Promise<unknown>>>;
  readonly chunkIds: readonly string[];
  importChunk(id: string): Promise<unknown>;
}

/** `entry` is a module path (vs. a bundler chunk name). */
export function isModuleEntry(entry: string): boolean {
  return /[\\/]/.test(entry) || /\.[cm]?[jt]sx?$/.test(entry);
}

/** File-safe chunk name for a logical id: `feature:studio` → `feature.studio`, `locale:de/studio` → `locale.de_studio`. */
export function chunkNameFor(id: string): string {
  return id.replace(/:/g, '.').replace(/[\\/]/g, '_');
}

export interface ModuleEntry {
  readonly id: string;
  readonly name: string;
  /** Absolute module path. */
  readonly file: string;
}

/** Declarations with a module-path entry, resolved against the project root. */
export function moduleEntries(declarations: readonly ChunkDeclaration[], root: string): readonly ModuleEntry[] {
  const out: ModuleEntry[] = [];
  for (const d of declarations) {
    if (d.entry === undefined || !isModuleEntry(d.entry)) continue;
    out.push({ id: d.id, name: chunkNameFor(d.id), file: isAbsolute(d.entry) ? d.entry : resolve(root, d.entry) });
  }
  return out;
}

const toPosix = (path: string): string => path.split(sep).join('/').replace(/\\/g, '/');

/** Source of `virtual:sf-chunks`. Deterministic (sorted by id). */
export function renderChunksModule(entries: readonly ModuleEntry[]): string {
  const sorted = [...entries].sort((a, b) => a.id.localeCompare(b.id));
  const lines = sorted.map((e) => `  ${JSON.stringify(e.id)}: () => import(${JSON.stringify(toPosix(e.file))}),`);
  return [
    '// Generated by @staticflux/vite-plugin: logical chunk id → import() thunk.',
    `export const chunks = Object.freeze({\n${lines.join('\n')}\n});`,
    'export const chunkIds = Object.freeze(Object.keys(chunks));',
    'export function importChunk(id) {',
    '  const load = chunks[id];',
    '  if (load === undefined) return Promise.reject(new Error(`SF-LOAD-001: chunk "${id}" is not declared in the staticflux() plugin.`));',
    '  return load();',
    '}',
    '',
  ].join('\n');
}

/** Dev-server URL of a source module (`/src/x.ts` inside root, `/@fs/abs` outside). */
export function devUrlOf(file: string, root: string): string {
  const rel = relative(root, file);
  if (rel.startsWith('..') || isAbsolute(rel)) return `/@fs${toPosix(file).startsWith('/') ? '' : '/'}${toPosix(file)}`;
  return `/${toPosix(rel)}`;
}

/**
 * Fake bundler output for the dev manifest: one "chunk" per module entry (the source module),
 * and the virtual chunks module for declarations that name a bundler chunk (no separate file in dev).
 */
export function devBundlerOutput(declarations: readonly ChunkDeclaration[], root: string): { readonly chunks: readonly BundlerChunk[] } {
  const chunks: BundlerChunk[] = [];
  const byId = new Map(moduleEntries(declarations, root).map((e) => [e.id, e]));
  for (const d of declarations) {
    const entry = byId.get(d.id);
    if (entry !== undefined) {
      chunks.push({ fileName: devUrlOf(entry.file, root), name: d.entry ?? d.id, moduleId: entry.file, imports: [] });
    } else {
      chunks.push({ fileName: DEV_VIRTUAL_CHUNKS_URL, name: d.entry ?? d.id, imports: [] });
    }
  }
  return { chunks };
}
